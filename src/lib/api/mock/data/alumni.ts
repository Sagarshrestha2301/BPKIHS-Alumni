const statusFor = (index: number): ApprovalStatus => {
  if (index % 30 === 22) return 'rejected';
  if (index % 15 === 7) return 'pending';
  return 'approved';
};

const profileVisibilityFor = (index: number): Visibility => {
  if (index % 10 === 3) return 'hidden';
  if (index % 4 === 0) return 'alumni_only';
  return 'public';
};

const emailVisibilityFor = (index: number): Visibility => {
  if (index % 3 === 0) return 'alumni_only';
  if (index % 7 === 0) return 'public';
  return 'hidden';
};

const phoneVisibilityFor = (index: number): Visibility =>
  index % 5 === 0 ? 'alumni_only' : 'hidden';

function emailFor(fullName: string): string {
  const words = fullName
    .toLowerCase()
    .replace(/[^a-z\s]/g, '')
    .split(/\s+/)
    .filter(Boolean);
  return `${words.join('.')}@example.com`;
}

